<h1>Handicap</h1>

<p>IdéesCulture a été sensibilisé à la prise en charge dès sa création. En 2014, nous avons mené avec le soutien de l'Incubateur Emergence de la Technopole Universitaire du Mans un audit de l'accessibilité de CollectiveAccess.</p>
<p>Nous poursuivons cette démarche dans nos développements logiciels (a11y-menu https://github.com/gautiermichelin/a11y-menu) mais aussi dans nos formations.</p>

<p>Si vous avez des besoins spécifiques, n'hésitez pas à nous contacter.</p>

<h2>Salle de formation</h2>
<p>Notre salle de réunion actuelle est malheureusement au 1er étage sans ascenseur. Nous pouvons organiser des formations dans des locaux accessibles sur demande, par exemple au sein de Regus, attenant à la gare TGV du Mans, ou à Créapolis (quartier gare sud).</p>

<h2>Handicap visuel</h2>
<p>CollectiveAccess est une application web dont les retours d'utilisation avec une synthèse vocale, comme JAWS, sont bons. Avec vos retours, nous l'améliorons sans cesse. Nos supports sont au format PDF ou directement en ligne, eux-même conçus pour être lus avec une synthèse vocale.</p>
<p>Dans une précédente vie professionnelle, Gautier Michelin a pu intervenir auprès de personnes malvoyantes pour les former à l'utilisation d'un système de gestion documentaire.</p>

<h2>Handicap auditif</h2>
<p>Nous n'avons pas d'expérience avec les boucles auditives, mais travaillons au quotidien en mode texte. Avec une retranscription en direct de l'audio, nous pouvons utiliser les outils modernes de visioconférence pour vous accueillir.</p>

<h2>Handicaps invisibles</h2>
<p>Nous sommes sensibles par nos profils aux handicaps invisibles, notamment les troubles de l'attention, les troubles de l'apprentissage, les troubles du spectre autistique. Nous pouvons adapter nos formations pour vous accueillir au mieux.</p>

